#include <dxgiformat.h>
#include "../interface/vertexLayout.h"
namespace IKIGAI::RENDER {
inline DXGI_FORMAT NativeVertexFormat(VertexFormat format) {
    static constexpr DXGI_FORMAT formats[] = {DXGI_FORMAT_R32_FLOAT,DXGI_FORMAT_R32G32_FLOAT,DXGI_FORMAT_R32G32B32_FLOAT,DXGI_FORMAT_R32G32B32A32_FLOAT,DXGI_FORMAT_R32_SINT,DXGI_FORMAT_R32G32_SINT,DXGI_FORMAT_R32G32B32_SINT,DXGI_FORMAT_R32G32B32A32_SINT,DXGI_FORMAT_R32_UINT,DXGI_FORMAT_R32G32_UINT,DXGI_FORMAT_R32G32B32_UINT,DXGI_FORMAT_R32G32B32A32_UINT,DXGI_FORMAT_R8G8B8A8_UNORM,DXGI_FORMAT_R8G8B8A8_SNORM};
    GetVertexFormatInfo(format);
    return formats[static_cast<unsigned>(format)];
}
}
#endif

